// Coupon at checkout, staff sold-out switch, WhatsApp notify link, sales report and the coupons card.
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const [SP, SITE = 'http://localhost:4313/', PANEL = 'http://localhost:3100'] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const errors = [];
const watch = (p, tag) => p.on('pageerror', (e) => errors.push(`${tag}: ${e.message}`));
const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
watch(m, 'site');
await m.goto(SITE, { waitUntil: 'load' });
await m.waitForTimeout(2500);
await m.evaluate(() => document.getElementById('cardapio').scrollIntoView());
await m.getByRole('tab', { name: 'Chefões' }).click();
await m.waitForTimeout(400);
await m.getByRole('button', { name: 'Adicionar El Patron' }).click();
await m.waitForTimeout(600);
await m.locator('dialog[open] form button[type=submit]').click();
await m.waitForTimeout(5500);
await m.evaluate(() => document.querySelector('button[aria-label*="Abrir sacola"]').click());
await m.waitForTimeout(700);
await m.getByRole('button', { name: 'Continuar' }).click();
const f = m.locator('dialog[open] form');
await f.getByLabel('Seu nome').fill('Marina Teste');
await f.getByLabel('Telefone (WhatsApp)').fill('11 98765-4321');
await f.getByText('Retirar no local', { exact: true }).click();
await f.getByText('Cartão no balcão', { exact: true }).click();
await f.getByLabel(/Cupom de desconto/).fill('nada');
await f.getByRole('button', { name: 'Aplicar' }).click();
await m.waitForTimeout(1200);
console.log('cupom inválido:', await f.locator('[id$=-coupon-msg]').innerText());
await f.getByLabel(/Cupom de desconto/).fill('patron10');
await f.getByRole('button', { name: 'Aplicar' }).click();
await m.waitForTimeout(1200);
await f.locator('.scroll-cream').evaluate((el) => el.scrollTo(0, el.scrollHeight));
await m.waitForTimeout(300);
await m.screenshot({ path: `${SP}/x-1-cupom.png` });
console.log('rodapé:', (await f.locator('footer dl').innerText()).replace(/\s+/g, ' '));
await f.locator('button[type=submit]').click();
await m.waitForURL(/\/pedido/, { timeout: 15000 });
await m.waitForTimeout(2500);
const trackUrl = m.url();

const d = await b.newPage({ viewport: { width: 1440, height: 950 } });
watch(d, 'loja');
await d.goto(`${PANEL}/login`);
await d.locator('input[name=email]').fill('caixa@teste.local');
await d.locator('input[name=senha]').fill('teste-1234-loja');
await d.locator('button[type=submit]').click();
await d.waitForURL(/\/loja\//);
await d.waitForTimeout(2500);
const card = d.locator('article', { hasText: '#1 ·' });
console.log('card tem cupom:', (await card.innerText()).includes('PATRON10'));
await card.getByRole('button', { name: 'Aceitar pedido' }).click();
await d.waitForTimeout(1500);
console.log('whatsapp:', decodeURIComponent((await card.getByRole('link', { name: /Avisar o cliente/ }).getAttribute('href')) ?? ''));
await d.screenshot({ path: `${SP}/x-2-loja.png` });

await d.getByRole('button', { name: /^Esgotados/ }).click();
await d.waitForTimeout(500);
await d.getByLabel('El Chapo esgotado').check();
await d.waitForTimeout(1500);
await d.screenshot({ path: `${SP}/x-3-esgotados.png` });
console.log('botão:', await d.getByRole('button', { name: /^Esgotados/ }).innerText());
await d.getByRole('button', { name: 'Fechar' }).click();

await m.goto(SITE, { waitUntil: 'load' });
await m.waitForTimeout(8000);
await m.evaluate(() => document.getElementById('cardapio').scrollIntoView());
await m.getByRole('tab', { name: 'Chefões' }).click();
await m.waitForTimeout(600);
const chapo = m.locator('#cat-chefoes article', { hasText: 'El Chapo' }).first();
console.log('site El Chapo:', (await chapo.innerText()).replace(/\s+/g, ' ').slice(0, 40), '· selos Esgotado:', await m.locator('#cat-chefoes').getByText('Esgotado', { exact: true }).count());
await chapo.screenshot({ path: `${SP}/x-4-site-esgotado.png` });

await m.goto(trackUrl, { waitUntil: 'load' });
await m.waitForTimeout(3000);
await m.screenshot({ path: `${SP}/x-5-acompanha.png`, fullPage: true });

await d.getByRole('link', { name: 'Relatório' }).click();
await d.waitForURL(/relatorio/);
await d.waitForTimeout(1000);
await d.screenshot({ path: `${SP}/x-6-relatorio.png`, fullPage: true });
const rp = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await rp.context().addCookies(await d.context().cookies());
await rp.goto(d.url());
await rp.screenshot({ path: `${SP}/x-7-relatorio-m.png`, fullPage: true });
console.log('relatório:', (await d.locator('section[aria-label=Resumo]').innerText()).replace(/\s+/g, ' '));

const t = await b.newPage({ viewport: { width: 1440, height: 1000 } });
watch(t, 'equipe');
await t.goto(`${PANEL}/login`);
await t.locator('input[name=email]').fill('equipe@teste.local');
await t.locator('input[name=senha]').fill('equipe-teste-123');
await t.locator('button[type=submit]').click();
await t.waitForURL(/\/painel/);
await t.goto(`${PANEL}/painel/lojas/el-patron-burger?aba=online`);
await t.waitForTimeout(1500);
await t.getByLabel('Código').fill('frete5');
await t.getByLabel('Tipo').selectOption('fixed');
await t.getByLabel('Desconto R$').fill('5');
await t.getByRole('button', { name: 'Criar cupom' }).click();
await t.waitForTimeout(500);
const sec = t.locator('section', { hasText: 'Cupons de desconto' });
await sec.scrollIntoViewIfNeeded();
await sec.screenshot({ path: `${SP}/x-8-cupons.png` });
console.log('cupons:', (await sec.locator('ul').innerText()).replace(/\s+/g, ' '));
console.log('erros:', errors);
await b.close();
