// Clube: opt-in + free-delivery coupon on the site, then the store's customers/campaign page.
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const [OUT, SITE = 'http://localhost:4313/', PANEL = 'http://localhost:3100'] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const errors = [];
const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
m.on('pageerror', (e) => errors.push('site: ' + e.message));
await m.goto(SITE, { waitUntil: 'load' });
await m.waitForTimeout(2500);
await m.evaluate(() => document.getElementById('cardapio').scrollIntoView());
await m.getByRole('tab', { name: 'Chefões' }).click();
await m.waitForTimeout(400);
await m.getByRole('button', { name: 'Adicionar Al Capone' }).click();
await m.waitForTimeout(600);
if (await m.locator('dialog[open] form').count()) await m.locator('dialog[open] form button[type=submit]').click();
await m.waitForTimeout(5500);
await m.evaluate(() => document.querySelector('button[aria-label*="Abrir sacola"]').click());
await m.waitForTimeout(700);
await m.getByRole('button', { name: 'Continuar' }).click();
const f = m.locator('dialog[open] form');
await f.getByLabel('Seu nome').fill('Larissa');
await f.getByLabel('Telefone (WhatsApp)').fill('11 94444-3333');
await f.getByLabel('Bairro').selectOption('teste-b');
await f.getByLabel('Endereço').fill('Rua das Flores, 80');
await f.getByText('Pix', { exact: true }).click();
await f.getByLabel(/Cupom de desconto/).fill('voltei');
await f.getByRole('button', { name: 'Aplicar' }).click();
await m.waitForTimeout(1200);
await f.getByText(/Quero receber promoções/).click();
await f.locator('.scroll-cream').evaluate((el) => el.scrollTo(0, el.scrollHeight));
await m.waitForTimeout(300);
await m.screenshot({ path: `${OUT}/checkout-clube-m.jpg`, type: 'jpeg', quality: 88 });
console.log('rodapé:', (await f.locator('footer dl').innerText()).replace(/\s+/g, ' '));
await f.locator('button[type=submit]').click();
await m.waitForURL(/\/pedido/, { timeout: 15000 });
await m.waitForTimeout(2000);
console.log('acompanhamento total:', (await m.locator('dl').last().innerText()).replace(/\s+/g, ' '));

const d = await b.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1.5 });
d.on('pageerror', (e) => errors.push('painel: ' + e.message));
await d.goto(`${PANEL}/login`);
await d.locator('input[name=email]').fill('caixa@teste.local');
await d.locator('input[name=senha]').fill('teste-1234-loja');
await d.locator('button[type=submit]').click();
await d.waitForURL(/\/loja\//);
await d.waitForTimeout(1500);
await d.getByRole('link', { name: 'Clientes' }).click();
await d.waitForURL(/clientes/);
await d.waitForTimeout(1000);
await d.getByLabel('Cupom da campanha').selectOption('VOLTEI');
await d.waitForTimeout(300);
console.log('mensagem:', await d.getByLabel('Mensagem').inputValue());
console.log('resumo:', (await d.locator('section[aria-label=Resumo]').innerText()).replace(/\s+/g, ' '));
const larissa = d.locator('li', { hasText: '94444-3333' });
console.log('larissa:', (await larissa.innerText()).replace(/\s+/g, ' '));
const [dl] = await Promise.all([d.waitForEvent('download'), d.getByRole('button', { name: /Baixar contatos/ }).click()]);
const path = `${OUT}/${dl.suggestedFilename()}`;
await dl.saveAs(path);
console.log('vcf:', path);
await d.screenshot({ path: `${OUT}/clientes-d.jpg`, type: 'jpeg', quality: 88 });
await d.screenshot({ path: `${OUT}/clientes-full.jpg`, type: 'jpeg', quality: 88, fullPage: true });
await larissa.getByRole('button', { name: 'Tirar das promoções' }).click();
await d.waitForTimeout(1500);
await d.reload();
await d.waitForTimeout(1000);
console.log('depois de tirar:', (await d.locator('li', { hasText: '94444-3333' }).innerText()).replace(/\s+/g, ' '));
console.log('erros:', errors);
await b.close();
